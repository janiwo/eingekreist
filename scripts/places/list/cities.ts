/**
 * Cities: OpenStreetMap administrative boundaries, by relation ID (looked up once via Nominatim).
 * Cities whose boundary is a whole province (e.g. Chongqing, Riyadh, Ankara) are left out.
 * Remote parts (islands far offshore) are excluded so the outline stays the city itself.
 */
const city = (id: string, name: string, relations: number[], exclude?: BBox[]): Entry => ({
  id,
  name,
  source: { kind: 'osm', relations },
  ...(exclude && { exclude }),
})

